# Callback fuer den Reset-Button registrieren
#-----------------------------------------------------------------------
def registerResetCallback (app, lock, latest):
	# Datenspeicher zuruecksetzen
	@app.callback(
		Output("reset_dummy", "children"),
		Input("btn_reset", "n_clicks"),
		prevent_initial_call=True,
	)
	def _resetData (_):
		with lock:
			latest["last_rx_ms"] = 0

		return ""

	return _resetData
